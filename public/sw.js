// Offline support for the installed app.
// Network first, so a running server always serves the latest build; every
// successful response is cached, and the cache is used when the network fails.
const CACHE = 'rhythm-trainer-v1';

self.addEventListener('install', () => self.skipWaiting());

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    fetch(req)
      .then((res) => {
        if (res.ok) {
          const copy = res.clone();
          e.waitUntil(caches.open(CACHE).then((c) => c.put(req, copy)));
        }
        return res;
      })
      .catch(async () => {
        const hit = await caches.match(req, { ignoreSearch: true });
        if (hit) return hit;
        // Offline navigation to any URL in scope: serve the cached page.
        if (req.mode === 'navigate') return (await caches.match('./')) ?? (await caches.match('./index.html'));
        return Response.error();
      }),
  );
});
